"""MSCI command id -> what C702::__runScript does for it: KC methods and natives each `case` calls.

    x3kc msci map <x3story.kc (kcd output)> <texts tsv> <out.md> [--json out.json]

The interpreter's big `switch (v18)` (v18 = command id of the current script line) is cut into its case
sections; the syntax of each id comes from text pages 2003, 302003 and 352003.
"""
import argparse
import json
import re
from collections import OrderedDict

CALL = re.compile(r'(?:\b(C\d+|\w+)\.)?\b([A-Za-z_]\w*)\(')
SKIP = {'if', 'while', 'for', 'switch', 'return', 'function'}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('src')
    ap.add_argument('texts')
    ap.add_argument('out')
    ap.add_argument('--json')
    a = ap.parse_args()
    syn = {}
    for line in open(a.texts, encoding='utf-8'):
        k, _, v = line.rstrip('\n').partition('\t')
        p, _, i = k.partition(':')
        if p in ('2003', '302003', '352003') and i.isdigit():
            syn.setdefault(int(i), v)
    lines = open(a.src, encoding='latin1').read().split('\n')
    start = next(k for k, l in enumerate(lines) if 'function __runScript(' in l)
    end = next(k for k in range(start, len(lines)) if lines[k] == '    }')
    body = lines[start:end]
    sw = next(k for k, l in enumerate(body) if re.match(r'\s+switch \(v18\) \{', l))
    ind = len(body[sw]) - len(body[sw].lstrip())
    case_re = re.compile(r'^' + ' ' * ind + r'(case (-?\d+)|default):')
    close = next(k for k in range(sw + 1, len(body)) if body[k] == ' ' * ind + '}')
    table = OrderedDict()
    cur = []
    body_seen = False           # labels share a group only when nothing stands between them
    last = ''
    for l in body[sw + 1:close]:
        m = case_re.match(l)
        if m:
            # a new group after a body that ends the case; a body that falls through runs the next case too
            if body_seen and re.match(r'\s*(break|return\b|continue)', last):
                cur = []
            body_seen = False
            if m.group(2) is not None:
                ids = int(m.group(2))
                cur.append((ids, []))
                table[ids] = cur
            continue
        if l.strip() and not l.strip().startswith('//'):
            body_seen = True
            if len(l) - len(l.lstrip()) == ind + 4:
                last = l                # last statement at the case body's own level
        if cur:
            for x in CALL.finditer(l.split('//')[0]):
                obj, fn = x.groups()
                if fn in SKIP:
                    continue
                name = '%s.%s' % (obj, fn) if obj and obj.startswith('C') and obj[1:].isdigit() else ('.' + fn if obj else fn)
                for _, calls in cur:
                    if name not in calls:
                        calls.append(name)
    out = ['# MSCI script commands and what the interpreter (C702::__runScript) calls for them', '',
           'Generated by `kc/msci_map.py`. `.Name` = method called by name on an object, `C150.Name` = static call on a',
           'class object, `SE_x` etc. = natives. Syntax from text pages 2003 / 302003 / 352003 (`%n` = arguments).', '',
           '| id | syntax | calls |', '|---|---|---|']
    res = {}
    for i in sorted(table):
        calls = next(c for k, c in table[i] if k == i)
        res[i] = {'syntax': syn.get(i, ''), 'calls': calls}
        out.append('| %d | %s | %s |' % (i, syn.get(i, '').replace('|', '\\|'), ', '.join(calls)))
    open(a.out, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    if a.json:
        json.dump(res, open(a.json, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    print(len(table), 'commands;', sum(1 for i in table if i in syn), 'with syntax')


if __name__ == '__main__':
    main()
