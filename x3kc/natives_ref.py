"""The natives reference: docs/natives/<GROUP>.md and README.md, generated from the spec files.

    x3kc natives-ref [DIR] [--check]

The spec files (x3kc/targets.py spec_files): docs/natives/spec_<GROUP>.jsonl, one per native group, and
spec_x3src.jsonl for the natives the x3_src engine adds. One JSON object per line; the fields are described in
FIELDS below (and in the README this writes). --check only validates: every name of x3kc/natives_ap.txt,
natives_fl.txt and natives_x3src.txt has exactly one entry, no entry names a native of no list, each entry sits in
its group's file (an engine native in spec_x3src.jsonl) and has the required fields; exit code 1 on a problem.
Without --check the reference is written to DIR (default: the checkout's docs/natives) after the same check.
"""
import argparse
import collections
import json
import os
import re
import sys

from . import targets

GROUPS = (                          # group: what its natives do
    ('SA', 'objects in space: ships, stations, sectors, docking, orders, cargo, weapons, cut-scene placement'),
    ('SE', 'the script engine: strings, arrays, tables, maths, texts, tasks, files, registry, the MSCI evaluator'),
    ('TI', 'timers: delays, interrupts, the game and real clocks, time warp'),
    ('B3D', '3D rendering: instance nodes, scenes, cameras, lights, textures, screen overlays, icons'),
    ('J3D', 'cut-scene jobs, takes and paths (in the B3D dispatcher)'),
    ('INS', 'the cockpit and its instruments: views, targets, radar, monitors, galaxy map, overlay icons, dust'),
    ('X2', 'game control: saves, settings, benchmark, controller tables, registry, game state'),
    ('STA', 'Steam achievements and stats (in the X2 dispatcher; stubs)'),
    ('P', 'the process and the platform: exit, input devices and key names, system flags, loading screen'),
    ('MOV', 'movies and voice streams'),
    ('SFX', 'sound: samples, 3D sounds, MOD music, volumes, EAX rooms'),
    ('GS', 'the gate network: routes between sectors, sector owners, gates'),
)
FIELDS = (
    ('name', 'the native as KC calls it (`GROUP_Name`)'),
    ('group', 'its group (the prefix); the file it is in: `spec_<group>.jsonl`, an engine native `spec_x3src.jsonl`'),
    ('index', 'its number in the AP exe\'s group dispatcher (the position in the group\'s name table); null when '
              'X3AP.exe lacks it; for an engine native: its number in the x3_src dispatcher of the AP build'),
    ('index_fl', 'the same in X3FL.exe (FL lacks `X2_GetModName`, so X2 and STA numbers after it are one lower; FL '
                 'adds two B3D natives); null when X3FL.exe lacks it; for an engine native: its number in the '
                 'x3_src dispatcher of the FL build'),
    ('handler', 'the address of its case in X3AP.exe (the code the dispatcher jumps to); for an engine native the '
                'x3_src file and function'),
    ('handler_fl', 'the same in X3FL.exe'),
    ('callable', 'present and false only for the seven upper-case `SFX_` names: sound bank flag names found among the '
                 'exe\'s strings, in no dispatcher\'s name table; a call answers int 0'),
    ('args', 'the arguments as `name:type`, comma-separated; several call forms separated by ` | ` (for example by '
             'argument count); empty when none are read'),
    ('returns', 'what the calling task gets back'),
    ('waits', 'the reference pass\'s verdict: true when the calling task can be suspended in the call (state 2, or a '
              'yield to the next frame) so that a savegame can hold its return address; false when every path '
              'answers at once. See "Waits and savegame return sites"'),
    ('summary', 'one sentence; `x3kc natives` prints it'),
    ('semantics', 'the full behaviour of the AP exe: arguments, checks, results, side effects, quirks'),
    ('fl', '`same`, or `differs: ...` (what X3FL.exe does differently), or `absent ...`'),
    ('x3_src', '`same`, or `differs: ...` (what the x3_src engine does differently, with the bugs.md id when there '
               'is one), or `new native ...` for the engine\'s own'),
    ('confidence', '`high` (the code paths were read and agree), `medium` (main path read, a helper or a field\'s '
                   'meaning taken on trust), `low` (helpers not read; take the text as a lead)'),
    ('bugs', 'a list: original bugs a script can hit (address, what the script sees, whether x3_src fixes or '
             'reproduces it, the bugs.md id)'),
    ('notes', 'evidence, addresses, naming remarks'),
)
REQUIRED = ('name', 'group', 'index', 'index_fl', 'handler', 'handler_fl', 'args', 'returns', 'waits', 'summary',
            'semantics', 'fl', 'x3_src', 'confidence')
CONFIDENCE = ('high', 'medium', 'low')
GENERATED = '<!-- generated by `x3kc natives-ref` from docs/natives/spec_*.jsonl; do not edit by hand, regenerate -->'


def lists():
    return {e: targets.read('natives_%s.txt' % e) for e in ('ap', 'fl', 'x3src')}


def check():
    """the problems of the spec files (empty when they are consistent with the native lists)"""
    out = []
    seen = collections.defaultdict(list)
    L = lists()
    every = L['ap'] | L['fl'] | L['x3src']
    for path, n, line, s in targets.spec_lines():
        fn = os.path.basename(path)
        name = s['name']
        where = '%s:%d %s' % (fn, n, name)
        seen[name].append(where)
        want = 'spec_x3src.jsonl' if name in L['x3src'] else 'spec_%s.jsonl' % name.split('_', 1)[0]
        if fn != want:
            out.append('%s: belongs in %s' % (where, want))
        if s.get('group') != name.split('_', 1)[0]:
            out.append('%s: group %r' % (where, s.get('group')))
        for k in REQUIRED:
            if k not in s:
                out.append('%s: no field %s' % (where, k))
        unknown = set(s) - {k for k, _ in FIELDS}
        if unknown:
            out.append('%s: unknown fields %s' % (where, ', '.join(sorted(unknown))))
        if not isinstance(s.get('waits'), bool):
            out.append('%s: waits is not true/false' % where)
        if s.get('confidence') not in CONFIDENCE:
            out.append('%s: confidence %r' % (where, s.get('confidence')))
        if 'bugs' in s and not (isinstance(s['bugs'], list) and all(isinstance(b, str) for b in s['bugs'])):
            out.append('%s: bugs is not a list of strings' % where)
        if name not in every:
            out.append('%s: in no native list (x3kc/natives_*.txt)' % where)
        if name in L['ap'] and s.get('index') is None and s.get('callable') is not False:
            out.append('%s: in X3AP.exe but no index' % where)
        if name in L['fl'] and s.get('index_fl') is None and s.get('callable') is not False:
            out.append('%s: in X3FL.exe but no index_fl' % where)
    for name, w in sorted(seen.items()):
        if len(w) > 1:
            out.append('%s: %d entries (%s)' % (name, len(w), ', '.join(w)))
    for name in sorted(every - set(seen)):
        out.append('%s: no entry' % name)
    return out


def md(s):
    """text for a Markdown paragraph or table cell"""
    s = ' '.join(str(s).split())
    return re.sub(r'([\\`*|<])', r'\\\1', s)


def code(s):
    s = ' '.join(str(s).split())
    return '``%s``' % s if '`' in s else '`%s`' % s


def exes(name):
    return targets.where_word(name) or '-'


def anchor(name):
    return name.lower()


def entries():
    """group -> (exe natives, engine natives), each sorted by number then name"""
    L = lists()
    out = collections.OrderedDict((g, ([], [])) for g, _ in GROUPS)
    for _, _, _, s in targets.spec_lines():
        g = s['name'].split('_', 1)[0]
        out.setdefault(g, ([], []))[1 if s['name'] in L['x3src'] else 0].append(s)

    def key(s):
        i = s.get('index') if s.get('index') is not None else s.get('index_fl')
        return (i if i is not None else 10 ** 6, s['name'])
    for g in out:
        out[g][0].sort(key=key)
        out[g][1].sort(key=key)
    return out


def counts(es):
    c = collections.Counter()
    for s in es:
        c['all'] += 1
        c['waits'] += bool(s.get('waits'))
        c[s.get('confidence')] += 1
        c['fl differs'] += str(s.get('fl', '')).startswith('differs')
        c['x3_src differs'] += str(s.get('x3_src', '')).startswith('differs')
        c['bugs'] += bool(s.get('bugs'))
    return c


def signature_lines(s):
    forms = [f.strip() for f in str(s.get('args', '')).split(' | ')] if s.get('args') else ['']
    return ['%s(%s)' % (s['name'], f) for f in forms]


def native_section(s):
    name = s['name']
    out = ['### %s' % name, '']
    for sig in signature_lines(s):
        out.append('    ' + sig)
    out.append('')
    facts = []
    if s.get('callable') is False:
        facts.append('**not a callable native** (a call answers int 0)')
    facts.append('returns %s' % md(s.get('returns', '?')))
    facts.append('**may wait**' if s.get('waits') else 'answers at once')
    facts.append('in %s' % exes(name))
    num = []
    if s.get('index') is not None:
        num.append('AP %s' % s['index'])
    if s.get('index_fl') is not None:
        num.append('FL %s' % s['index_fl'])
    if num:
        facts.append('number ' + ', '.join(num))
    hd = []
    if s.get('handler'):
        hd.append(code(s['handler']) + (' (AP)' if s.get('handler_fl') and s['handler_fl'] != s['handler'] else ''))
    if s.get('handler_fl') and s.get('handler_fl') != s.get('handler'):
        hd.append(code(s['handler_fl']) + ' (FL)')
    if hd:
        facts.append('handler ' + ', '.join(hd))
    facts.append('confidence %s' % s.get('confidence', '?'))
    out += ['; '.join(facts) + '.', '']
    if s.get('summary'):
        out += ['**%s**' % md(s['summary']), '']
    if s.get('semantics'):
        out += [md(s['semantics']), '']
    out.append('- **FL:** %s' % md(s.get('fl', '?')))
    out.append('- **x3_src:** %s' % md(s.get('x3_src', '?')))
    for i, b in enumerate(s.get('bugs') or []):
        out.append('- **Bug%s:** %s' % (' %d' % (i + 1) if len(s['bugs']) > 1 else '', md(b)))
    if s.get('notes'):
        out.append('- **Notes:** %s' % md(s['notes']))
    out.append('')
    return out


def group_page(g, what, own, eng):
    allv = own + eng
    c = counts(allv)
    out = ['# %s natives' % g, '', GENERATED, '',
           '%s. %d natives%s: %d may wait; confidence %d high, %d medium, %d low; FL differs in %d, x3_src in %d; '
           '%d with original bugs. Fields and how to read an entry: [README.md](README.md).'
           % (what[0].upper() + what[1:], len(allv), ' (%d of them the x3_src engine\'s own)' % len(eng) if eng else '',
              c['waits'], c['high'], c['medium'], c['low'], c['fl differs'], c['x3_src differs'], c['bugs']), '',
           '| native | arguments | returns | waits | in | summary |', '|---|---|---|---|---|---|']
    for s in allv:
        out.append('| [%s](#%s) | %s | %s | %s | %s | %s |' % (
            s['name'], anchor(s['name']), md(s.get('args', '')), md(s.get('returns', '')),
            'may wait' if s.get('waits') else 'at once', exes(s['name']), md(s.get('summary', ''))))
    out.append('')
    if own:
        out += ['## Natives of the exes', '']
        for s in own:
            out += native_section(s)
    if eng:
        out += ['## Natives of the x3_src engine', '',
                'Only in the x3_src engine (both editions); the original exes answer int 0 at once. Their entries '
                'are in spec_x3src.jsonl.', '']
        for s in eng:
            out += native_section(s)
    return '\n'.join(out).rstrip('\n') + '\n'


README_BODY = '''\
The behaviour of every native function a KC script object can call (`GROUP_Name(...)`, opcode 0x82): what it
reads, what it answers, whether the calling task waits, how Farnham's Legacy and the x3_src engine differ, and the
original bugs a script can hit. Read from the dispatchers and handlers of X3AP.exe and X3FL.exe (disassembly) and
from the x3_src engine's source. The data is in the spec files next to this page, one JSON object per line:
`spec_<GROUP>.jsonl` per group, `spec_x3src.jsonl` for the natives the x3_src engine adds. The pages below are
generated from them (`x3kc natives-ref`; `x3kc natives-ref --check` validates them against the native lists
`x3kc/natives_ap.txt`, `natives_fl.txt`, `natives_x3src.txt`). At the command line `x3kc natives [prefix]` prints
one line per native (the summary) and `x3kc natives --full <prefix>` every field; the KC language server shows the
entry on hover and jumps to it on "go to definition".
'''

WAITS_TEXT = '''\
## Waits and savegame return sites

A native either answers at once (its handler resumes the task before the dispatcher returns, and the script goes
on in the same step) or leaves the task waiting: state 2 until an event answers it (a timer, a flight order
reaching its goal, a sound ending, a job finishing), or a yield that ends the scheduler's frame (`P_LoadLocation`).
While a task waits its pc - the address after the call - is what a savegame stores. So every call site of a
native that may wait, and every call of a method that can reach one, is a **savegame return site**: a mod that
moves or removes such a site breaks the savegames made while a task waited there (`x3kc compile --base`,
`x3kc savecheck`, docs/kc.md).

The field `waits` is the reference pass's verdict per native. x3kc itself decides at-once natives from its lists
`x3kc/sync_natives_ap.txt`, `sync_natives_fl.txt`, `sync_natives_x3src.txt` (x3kc/targets.py); a native in no
at-once list counts as possibly waiting. Where the two disagree, and what following the pass would change in the
x3_src objects' return sites: [sync_review.md](sync_review.md). A native that answers at once on its normal path
but never answers on an error path (for example `INS_CockpitSetTracking` with an unknown cockpit) has `waits`
false here; its bug entry says so.
'''

COLUMNS_TEXT = '''\
## The FL and x3_src columns

`fl` compares X3FL.exe with X3AP.exe, `x3_src` compares the x3_src engine with X3AP.exe (both editions' builds;
an FL-only difference of the engine is named). `same` means the code paths were compared and agree for a script
(an FL handler inlined differently is still `same`); `differs: ...` says how; `absent ...` that the exe lacks the
native (a call of a name the exe lacks answers int 0 at once). A difference in x3_src is a fixed original bug
(with its bugs.md id) or an engine extension (UI scale, GameInput devices, RNG channels, the overlay folder).
Bugs the engine keeps on purpose are in `bugs` with "x3_src reproduces".

## Confidence

`high`: every path that decides the result was read and the text checked against the code. `medium`: the main
path was read, a helper's effect or a field's meaning is taken from its name or from x3_src. `low`: helpers were
not read; take the text as a lead, not as fact.
'''


def readme(groups):
    L = lists()
    out = ['# Natives reference', '', GENERATED, '', README_BODY,
           '| group | what | natives | AP | FL | x3_src own | may wait | high / medium / low |',
           '|---|---|---|---|---|---|---|---|']
    tot = collections.Counter()
    for g, what in GROUPS:
        own, eng = groups.get(g, ([], []))
        allv = own + eng
        if not allv:
            continue
        c = counts(allv)
        ap = sum(1 for s in allv if s['name'] in L['ap'])
        fl = sum(1 for s in allv if s['name'] in L['fl'])
        out.append('| [%s](%s.md) | %s | %d | %d | %d | %d | %d | %d / %d / %d |' % (
            g, g, what, len(allv), ap, fl, len(eng), c['waits'], c['high'], c['medium'], c['low']))
        for k, v in (('all', len(allv)), ('ap', ap), ('fl', fl), ('eng', len(eng)), ('waits', c['waits']),
                     ('high', c['high']), ('medium', c['medium']), ('low', c['low'])):
            tot[k] += v
    out.append('| all | | %d | %d | %d | %d | %d | %d / %d / %d |' % (
        tot['all'], tot['ap'], tot['fl'], tot['eng'], tot['waits'], tot['high'], tot['medium'], tot['low']))
    out += ['', 'AP and FL count the natives of each exe (`x3kc/natives_ap.txt`, `natives_fl.txt`; the seven '
            'upper-case `SFX_` flag names included, see `callable`); "x3_src own" the engine\'s additions '
            '(`natives_x3src.txt`).', '', '## Fields', '']
    for k, t in FIELDS:
        out.append('- `%s`: %s' % (k, t))
    out += ['', 'A group page shows per native: the call forms, what it returns, whether it waits, which exes '
            'have it, its numbers and handlers, the confidence, the summary, the full semantics, the FL and x3_src '
            'differences, its bugs and notes.', '', WAITS_TEXT, COLUMNS_TEXT]
    return '\n'.join(out).rstrip('\n') + '\n'


def write(d):
    groups = entries()
    written = []
    for g, what in GROUPS:
        own, eng = groups.get(g, ([], []))
        if own or eng:
            p = os.path.join(d, '%s.md' % g)
            with open(p, 'w', encoding='utf-8', newline='\n') as f:
                f.write(group_page(g, what, own, eng))
            written.append(p)
    p = os.path.join(d, 'README.md')
    with open(p, 'w', encoding='utf-8', newline='\n') as f:
        f.write(readme(groups))
    written.append(p)
    return written


def main():
    ap = argparse.ArgumentParser(prog='x3kc natives-ref', description='Write the natives reference (one page per '
                                 'group and README.md) from docs/natives/spec_*.jsonl, after checking the spec '
                                 'files against the native lists.')
    ap.add_argument('dir', nargs='?', default=targets.SPEC_DIR, help='where to write (default %(default)s)')
    ap.add_argument('--check', action='store_true', help='only check the spec files')
    a = ap.parse_args()
    problems = check()
    for p in problems:
        print(p, file=sys.stderr)
    n = len(targets.specs())
    print('%d spec entries, %d problems' % (n, len(problems)))
    if problems:
        return 1
    if not a.check:
        for p in write(a.dir):
            print('wrote', p)
    return 0
